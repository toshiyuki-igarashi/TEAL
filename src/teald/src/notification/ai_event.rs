//! Convert a high-confidence AI suspected attack detection into a mail notification.
//!
//! AI analysis is independent of the access decision: notifications are emitted
//! even if the underlying action was ALLOWed or has already completed.
//! Only detections meeting or exceeding `min_confidence` (default: 0.95) are queued.

use std::sync::OnceLock;

use teal_notify_protocol::{
    AiNotification, NotificationPayload, NotificationRequest, MAX_RECIPIENTS, PROTOCOL_VERSION,
};

use super::{deny_event::cached_hostname, global_handle, EnqueueError, NotificationHandle};

pub const DEFAULT_MIN_CONFIDENCE: f64 = 0.95;

const MAX_ID_BYTES: usize = 128;
const MAX_HOST_BYTES: usize = 255;
const MAX_PROGRAM_BYTES: usize = 4096;
const MAX_ACTION_BYTES: usize = 64;
const MAX_TARGET_BYTES: usize = 4096;
const MAX_REASON_BYTES: usize = 16 * 1024;
const MAX_EMAIL_BYTES: usize = 320;
const MAX_RELATED_EVENT_IDS: usize = 128;

#[derive(Debug, Clone)]
pub struct AiAttackEvent<'a> {
    /// Unique analysis or event identifier.
    pub analysis_id: &'a str,
    /// Host where the activity was detected. Defaults to local host if empty.
    pub hostname: &'a str,
    /// Model confidence score (0.0 ..= 1.0).
    pub confidence: f64,
    /// Explanation or summary generated by the AI runtime.
    pub reason: &'a str,
    /// Related ALLOW/AuditOnly audit event IDs used as AI evidence (not DENY IDs).
    pub related_event_ids: &'a [&'a str],
    /// Program path involved in the suspicious behavior.
    pub program: &'a str,
    /// Security action performed or attempted.
    pub action: &'a str,
    /// Target path or network destination.
    pub target: &'a str,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum AiSubmitError {
    Uninitialized,
    LowConfidence { confidence: f64, threshold: f64 },
    InvalidData(&'static str),
    Enqueue(EnqueueError),
}

fn nonempty_bounded(s: &str, max: usize) -> bool {
    !s.trim().is_empty() && s.len() <= max && !s.chars().any(char::is_control)
}

/// Active threshold configured at runtime. Initialized with DEFAULT_MIN_CONFIDENCE.
static MIN_CONFIDENCE_THRESHOLD: OnceLock<f64> = OnceLock::new();

pub fn set_min_confidence(threshold: f64) -> Result<(), f64> {
    if !threshold.is_finite() || !(0.0..=1.0).contains(&threshold) {
        return Err(threshold);
    }
    MIN_CONFIDENCE_THRESHOLD
        .set(threshold)
        .map_err(|_| threshold)
}

pub fn min_confidence() -> f64 {
    *MIN_CONFIDENCE_THRESHOLD.get_or_init(|| DEFAULT_MIN_CONFIDENCE)
}

/// Pure conversion and validation without global daemon state.
/// Useful for isolated unit testing and mock injection.
pub fn build_request(
    event: AiAttackEvent<'_>,
    threshold: f64,
    bcc_recipients: &[String],
) -> Result<NotificationRequest, AiSubmitError> {
    if !event.confidence.is_finite() || !(0.0..=1.0).contains(&event.confidence) {
        return Err(AiSubmitError::InvalidData("invalid confidence value"));
    }
    if event.confidence < threshold {
        return Err(AiSubmitError::LowConfidence {
            confidence: event.confidence,
            threshold,
        });
    }

    if !nonempty_bounded(event.analysis_id, MAX_ID_BYTES - "AI-".len()) {
        return Err(AiSubmitError::InvalidData("invalid analysis ID"));
    }

    let host = if event.hostname.trim().is_empty() {
        cached_hostname()
    } else {
        event.hostname
    };
    if !nonempty_bounded(host, MAX_HOST_BYTES) {
        return Err(AiSubmitError::InvalidData("invalid hostname"));
    }

    if !nonempty_bounded(event.program, MAX_PROGRAM_BYTES) {
        return Err(AiSubmitError::InvalidData("invalid program"));
    }
    if !nonempty_bounded(event.action, MAX_ACTION_BYTES) {
        return Err(AiSubmitError::InvalidData("invalid action"));
    }
    if !nonempty_bounded(event.target, MAX_TARGET_BYTES) {
        return Err(AiSubmitError::InvalidData("invalid target"));
    }
    if !nonempty_bounded(event.reason, MAX_REASON_BYTES) {
        return Err(AiSubmitError::InvalidData("invalid reason text"));
    }

    if event.related_event_ids.len() > MAX_RELATED_EVENT_IDS {
        return Err(AiSubmitError::InvalidData("too many related event IDs"));
    }
    for id in event.related_event_ids {
        if !nonempty_bounded(id, MAX_ID_BYTES) {
            return Err(AiSubmitError::InvalidData("invalid related event ID"));
        }
    }

    if bcc_recipients.len() > MAX_RECIPIENTS
        || bcc_recipients
            .iter()
            .any(|s| !nonempty_bounded(s, MAX_EMAIL_BYTES))
    {
        return Err(AiSubmitError::InvalidData("invalid Bcc recipients"));
    }

    let request = NotificationRequest {
        version: PROTOCOL_VERSION,
        notification_id: format!("AI-{}", event.analysis_id),
        recipients: bcc_recipients.to_vec(),
        payload: NotificationPayload::Ai(AiNotification {
            hostname: host.to_owned(),
            confidence: event.confidence,
            reason: event.reason.to_owned(),
            related_event_ids: event
                .related_event_ids
                .iter()
                .map(|&s| s.to_owned())
                .collect(),
            program: event.program.to_owned(),
            action: event.action.to_owned(),
            target: event.target.to_owned(),
        }),
    };
    request.validate().map_err(AiSubmitError::InvalidData)?;
    Ok(request)
}

/// Enqueue a high-confidence attack detection without waiting for IPC/SMTP.
/// Returns immediately to ensure the AI analysis thread is never blocked.
pub fn submit(event: AiAttackEvent<'_>, bcc_recipients: &[String]) -> Result<(), AiSubmitError> {
    let handle = global_handle().ok_or(AiSubmitError::Uninitialized)?;
    let request = build_request(event, min_confidence(), bcc_recipients)?;
    handle
        .try_enqueue_ai(request)
        .map_err(AiSubmitError::Enqueue)
}

/// Direct enqueue for isolated unit tests using an explicit NotificationHandle.
pub fn enqueue_to(
    handle: &NotificationHandle,
    event: AiAttackEvent<'_>,
    threshold: f64,
    bcc_recipients: &[String],
) -> Result<(), AiSubmitError> {
    let request = build_request(event, threshold, bcc_recipients)?;
    handle
        .try_enqueue_ai(request)
        .map_err(AiSubmitError::Enqueue)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::notification::queue::{NotificationCounters, NotificationHandle};
    use std::sync::Arc;
    use tokio::sync::mpsc;

    fn sample_event() -> AiAttackEvent<'static> {
        AiAttackEvent {
            analysis_id: "ANL-998877",
            hostname: "server01",
            confidence: 0.98,
            reason: "Heuristic match: Mass credential modification and defense evasion.",
            related_event_ids: &["EVT-1001", "EVT-1002"],
            program: "/usr/bin/python3",
            action: "FILE_WRITE",
            target: "/etc/shadow",
        }
    }

    #[test]
    fn accepts_high_confidence_event() {
        let req = build_request(sample_event(), 0.95, &[]).unwrap();
        assert_eq!(req.notification_id, "AI-ANL-998877");
        if let NotificationPayload::Ai(ai) = req.payload {
            assert_eq!(ai.confidence, 0.98);
            assert_eq!(ai.related_event_ids, vec!["EVT-1001", "EVT-1002"]);
            assert_eq!(ai.target, "/etc/shadow");
        } else {
            panic!("expected AI payload");
        }
    }

    #[test]
    fn rejects_low_confidence_event() {
        let mut e = sample_event();
        e.confidence = 0.9499;
        assert_eq!(
            build_request(e, 0.95, &[]).unwrap_err(),
            AiSubmitError::LowConfidence {
                confidence: 0.9499,
                threshold: 0.95,
            }
        );
    }

    #[test]
    fn rejects_nan_or_out_of_range_confidence() {
        let mut e = sample_event();
        e.confidence = f64::NAN;
        assert!(matches!(
            build_request(e, 0.95, &[]),
            Err(AiSubmitError::InvalidData(_))
        ));

        let mut e = sample_event();
        e.confidence = 1.05;
        assert!(matches!(
            build_request(e, 0.95, &[]),
            Err(AiSubmitError::InvalidData(_))
        ));
    }

    #[test]
    fn pushes_ai_into_dedicated_bounded_queue() {
        let (ai_tx, mut ai_rx) = mpsc::channel(1);
        let (deny_tx, _deny_rx) = mpsc::channel(1);
        let handle =
            NotificationHandle::new(ai_tx, deny_tx, Arc::new(NotificationCounters::default()));

        enqueue_to(&handle, sample_event(), 0.95, &[]).unwrap();
        assert_eq!(handle.stats().ai_enqueued, 1);

        // Queue full must fail non-blocking without affecting counters of DENY
        assert_eq!(
            enqueue_to(&handle, sample_event(), 0.95, &[]),
            Err(AiSubmitError::Enqueue(EnqueueError::QueueFull))
        );
        assert_eq!(handle.stats().ai_queue_full, 1);
        assert_eq!(handle.stats().deny_enqueued, 0);

        let received = ai_rx.try_recv().unwrap();
        assert_eq!(received.notification_id, "AI-ANL-998877");
    }

    #[test]
    fn sanitizes_and_rejects_control_characters() {
        let mut e = sample_event();
        e.reason = "Suspicious\nBcc: evil@example.com";
        assert_eq!(
            build_request(e, 0.95, &[]).unwrap_err(),
            AiSubmitError::InvalidData("invalid reason text")
        );
    }
}
